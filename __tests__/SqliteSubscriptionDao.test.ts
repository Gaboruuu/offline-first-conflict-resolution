import { fromRow, migrate, MIGRATIONS, SqlDatabase, SqliteSubscriptionDao, toRowValues } from '@/data/SqliteSubscriptionDao';
import { NewSubscription } from '@/model/Subscription';

const netflix: NewSubscription = {
  name: 'Netflix',
  amount: 49.99,
  currency: 'RON',
  billingCycle: 'MONTHLY',
  nextPaymentDate: '2026-11-04',
  category: 'ENTERTAINMENT',
  isActive: true,
  notes: 'Shared',
};

const netflixRow = {
  id: 3, name: 'Netflix', amount_cents: 4999, currency: 'RON', billing_cycle: 'MONTHLY',
  next_payment_date: '2026-11-04', category: 'ENTERTAINMENT', is_active: 1, notes: 'Shared',
  server_id: 12, sync_state: 'SYNCED',
};

/** Records every statement and answers with the configured results. */
function fakeDb({ userVersion = 0, changes = 1, lastInsertRowId = 7, rows = [] as unknown[], first = null as unknown } = {}) {
  const statements: { sql: string; params?: unknown }[] = [];
  const db = {
    execAsync: jest.fn(async (sql: string) => {
      statements.push({ sql });
    }),
    runAsync: jest.fn(async (sql: string, params: unknown) => {
      statements.push({ sql, params });
      return { changes, lastInsertRowId };
    }),
    getAllAsync: jest.fn(async (sql: string) => {
      statements.push({ sql });
      return rows;
    }),
    getFirstAsync: jest.fn(async (sql: string) => (sql.startsWith('PRAGMA') ? { user_version: userVersion } : first)),
    withTransactionAsync: jest.fn(async (task: () => Promise<void>) => task()),
  };
  return { db: db as unknown as SqlDatabase, statements };
}

const squash = (sql: string) => sql.replace(/\s+/g, ' ').trim();

beforeAll(() => {
  jest.spyOn(console, 'log').mockImplementation(() => {});
});

describe('SqliteSubscriptionDao', () => {
  it('maps every field, the server id and the sync state to a row and back (amount in cents)', () => {
    expect(toRowValues(netflix, 12, 'SYNCED')).toEqual(
      ['Netflix', 4999, 'RON', 'MONTHLY', '2026-11-04', 'ENTERTAINMENT', 1, 'Shared', 12, 'SYNCED'],
    );
    expect(fromRow({ ...netflixRow, is_active: 0 })).toEqual({ ...netflix, id: 3, isActive: false, serverId: 12, syncState: 'SYNCED' });
    expect(fromRow({ ...netflixRow, server_id: null, sync_state: 'PENDING_CREATE' })).toMatchObject({ serverId: null, syncState: 'PENDING_CREATE' });
    expect(toRowValues({ ...netflix, amount: 0.29 }, null, 'PENDING_CREATE')[1]).toBe(29); // 0.29 * 100 = 28.999…
  });

  it('inserts only the new element and returns the local id generated by the database', async () => {
    const { db, statements } = fakeDb({ lastInsertRowId: 42 });
    const dao = new SqliteSubscriptionDao(async () => db);
    expect(await dao.insert(netflix, null, 'PENDING_CREATE')).toBe(42);
    expect(statements).toHaveLength(1);
    expect(squash(statements[0].sql)).toMatch(/^INSERT INTO subscriptions \(name, .*server_id, sync_state\) VALUES/);
    expect(statements[0].sql).not.toMatch(/\bid\b/);
    expect(statements[0].params).toEqual(toRowValues(netflix, null, 'PENDING_CREATE'));
  });

  it('updates the existing row in place, by local id', async () => {
    const { db, statements } = fakeDb();
    const dao = new SqliteSubscriptionDao(async () => db);
    const edited = { ...netflix, id: 5, amount: 59.99, serverId: 12, syncState: 'PENDING_UPDATE' as const };
    expect(await dao.update(edited)).toBe(true);
    expect(statements).toHaveLength(1);
    expect(squash(statements[0].sql)).toMatch(/^UPDATE subscriptions SET .* WHERE id = \?$/);
    expect(statements[0].params).toEqual([...toRowValues(edited, 12, 'PENDING_UPDATE'), 5]);
  });

  it('deletes using only the id', async () => {
    const { db, statements } = fakeDb({ changes: 0 });
    const dao = new SqliteSubscriptionDao(async () => db);
    expect(await dao.delete(5)).toBe(false);
    expect(statements).toEqual([{ sql: 'DELETE FROM subscriptions WHERE id = ?', params: [5] }]);
  });

  it('deletes and queues the server delete in one transaction', async () => {
    const { db, statements } = fakeDb();
    const dao = new SqliteSubscriptionDao(async () => db);
    expect(await dao.delete(5, 12)).toBe(true);
    expect(db.withTransactionAsync).toHaveBeenCalledTimes(1);
    expect(statements).toEqual([
      { sql: 'DELETE FROM subscriptions WHERE id = ?', params: [5] },
      { sql: 'INSERT OR IGNORE INTO pending_deletes (server_id) VALUES (?)', params: [12] },
    ]);
  });

  it('reads every row sorted by next payment date', async () => {
    const { db, statements } = fakeDb({ rows: [netflixRow] });
    const dao = new SqliteSubscriptionDao(async () => db);
    expect(await dao.getAll()).toEqual([{ ...netflix, id: 3, serverId: 12, syncState: 'SYNCED' }]);
    expect(statements[0].sql).toMatch(/ORDER BY next_payment_date/);
  });

  it('reads the queued deletes and the last sync time', async () => {
    const { db } = fakeDb({ rows: [{ server_id: 4 }, { server_id: 9 }], first: { value: '2026-11-05T10:00:00.000Z' } });
    const dao = new SqliteSubscriptionDao(async () => db);
    expect(await dao.getPendingDeletes()).toEqual([4, 9]);
    expect(await dao.getLastSyncedAt()).toBe('2026-11-05T10:00:00.000Z');
  });

  it('propagates database errors to the caller', async () => {
    const { db } = fakeDb();
    (db.runAsync as jest.Mock).mockRejectedValueOnce(new Error('SQLITE_FULL'));
    const dao = new SqliteSubscriptionDao(async () => db);
    await expect(dao.insert(netflix, null, 'PENDING_CREATE')).rejects.toThrow('SQLITE_FULL');
  });
});

describe('migrate', () => {
  it('creates the whole schema on a new database, in one transaction, without demo rows', async () => {
    const { db, statements } = fakeDb({ userVersion: 0 });
    await migrate(db);
    expect(db.withTransactionAsync).toHaveBeenCalledTimes(1);
    expect(statements[0].sql).toMatch(/CREATE TABLE IF NOT EXISTS subscriptions/);
    expect(statements[1].sql).toMatch(/ADD COLUMN server_id/);
    expect(statements[1].sql).toMatch(/CREATE TABLE IF NOT EXISTS pending_deletes/);
    expect(statements.filter((s) => s.sql.startsWith('INSERT'))).toHaveLength(0);
    expect(statements[statements.length - 1].sql).toBe(`PRAGMA user_version = ${MIGRATIONS.length}`);
  });

  it('upgrades a local-only database: only the sync columns and tables are added', async () => {
    const { db, statements } = fakeDb({ userVersion: 1 });
    await migrate(db);
    expect(statements).toHaveLength(2);
    expect(statements[0].sql).not.toMatch(/CREATE TABLE IF NOT EXISTS subscriptions/);
    // Rows from the local-only version were never on the server, so they will be uploaded.
    expect(statements[0].sql).toMatch(/sync_state TEXT NOT NULL DEFAULT 'PENDING_CREATE'/);
  });

  it('does nothing on an up-to-date database', async () => {
    const { db, statements } = fakeDb({ userVersion: MIGRATIONS.length });
    await migrate(db);
    expect(statements).toHaveLength(0);
    expect(db.withTransactionAsync).not.toHaveBeenCalled();
  });
});
