import { NewSubscription, Subscription } from '@/model/Subscription';

/**
 * Whether the local row matches the server: `PENDING_CREATE` rows were never sent (no server id yet),
 * `PENDING_UPDATE` rows have local changes the server has not received.
 */
export type SyncState = 'SYNCED' | 'PENDING_CREATE' | 'PENDING_UPDATE';

/**
 * A subscription as stored on the phone. `id` is the local row id (the app's key for screens and
 * lists); `serverId` is the id assigned by the server, `null` until the server has stored it.
 * Neither id is ever shown to the user.
 */
export interface LocalSubscription extends Subscription {
  readonly serverId: number | null;
  readonly syncState: SyncState;
}

/**
 * Persistence operations on the local database. Every write touches exactly one row, identified by
 * its local id. Implementations reject the promise on failure.
 */
export interface SubscriptionDao {
  /** Every stored subscription, sorted by next payment date. */
  getAll(): Promise<LocalSubscription[]>;
  /** Inserts the element and returns the local id generated by the database. */
  insert(subscription: NewSubscription, serverId: number | null, syncState: SyncState): Promise<number>;
  /** Updates the row with the same local id in place (fields, server id and sync state). False if missing. */
  update(subscription: LocalSubscription): Promise<boolean>;
  /**
   * Deletes the row with this local id. With [queueServerDelete], also remembers (in the same
   * transaction) that the server element with that id must be deleted once online. False if missing.
   */
  delete(id: number, queueServerDelete?: number): Promise<boolean>;
  /** Server ids of the elements deleted offline, oldest first. */
  getPendingDeletes(): Promise<number[]>;
  removePendingDelete(serverId: number): Promise<void>;
  /** When the list was last refreshed from the server (ISO timestamp), or null if never. */
  getLastSyncedAt(): Promise<string | null>;
  setLastSyncedAt(timestamp: string): Promise<void>;
}
